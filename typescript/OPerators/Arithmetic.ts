{
    //write Arithmetic operators in TypeScript
    let x: number = 10;
    let y: number = 20;
    let z: number;

    z = x + y; // Addition
    console.log("Addition: " + z); // Output: Addition: 30

    z = x - y; // Subtraction
    console.log("Subtraction: " + z); // Output: Subtraction: -10

    z = x * y; // Multiplication
    console.log("Multiplication: " + z); // Output: Multiplication: 200

    z = x / y; // Division
    console.log("Division: " + z); // Output: Division: 0.5

    z = x % y; // Modulus
    console.log("Modulus: " + z); // Output: Modulus: 10        
}