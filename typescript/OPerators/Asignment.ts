{
    let a: number = 10;

    a *= 20; /// a = a * 20; // a is now 200
    a/=5; /// a = a / 5; // a is now 40
    a+=10; /// a = a + 10; // a is now 50
    a-=5; /// a = a - 5; // a is now 45
    a%=6; /// a = a % 6; // a is now 3

    console.log("The final value of a is: " + a); // Output: The final value of a is: 3
}